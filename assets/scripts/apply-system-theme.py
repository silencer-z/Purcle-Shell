def gtk_colors_css(colors: dict[str, str]) -> str:
    require(
        colors,
        "base", "mantle", "surface0", "text", "overlay0", "mauve",
        "onPrimary", "red", "blue", "teal",
    )
    tokens = {
        "background": colors["base"],
        "foreground": colors["text"],
        "surface": colors["surface0"],
        "surface_dim": colors["mantle"],
        "primary": colors["mauve"],
        "on_primary": colors["onPrimary"],
        "secondary": colors["blue"],
        "on_secondary": colors["onPrimary"],
        "tertiary": colors["teal"],
        "on_tertiary": colors["onPrimary"],
        "error": colors["red"],
        "on_error": colors["onPrimary"],
        "error_container": colors["surface0"],
        "outline": colors["overlay0"],
    }
    lines = [
        "/* Generated by PurcleShell. Do not edit. */",
        "",
    ]
    for name, value in tokens.items():
        lines.append(f"@define-color {name} {value};")
    lines.append("")
    return "\n".join(lines) + "\n"


def gtk_shell_css() -> str:
    return (
        "/* PurcleShell gtk color mapping */\n"
        "@import './colors.css';\n"
        "\n"
        + GTK_WIDGET_MAP
    )


def patch_settings_ini(path: Path, dark: bool) -> None:
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    prefer = "1" if dark else "0"
    text = patch_ini_key(text, "gtk-application-prefer-dark-theme", prefer)
    atomic_write(path, text if text.endswith("\n") else text + "\n")


def write_gtk(home: Path, colors: dict[str, str], dark: bool) -> None:
    css = gtk_colors_css(colors)
    gtk3 = home / ".config/gtk-3.0"
    gtk4 = home / ".config/gtk-4.0"
    atomic_write(gtk3 / "colors.css", css)
    atomic_write(gtk4 / "colors.css", css)

    gtk3_css = gtk3 / "gtk.css"
    if not gtk3_css.exists() or "@import './colors.css'" not in gtk3_css.read_text(encoding="utf-8", errors="ignore"):
        atomic_write(gtk3_css, gtk_shell_css())

    gtk4_css = gtk4 / "gtk.css"
    managed = False
    if gtk4_css.exists():
        current = gtk4_css.read_text(encoding="utf-8", errors="ignore")
        managed = current.lstrip().startswith("/* PurcleShell") or (
            current.lstrip().startswith("@import './colors.css'") and len(current) < 4000
        )
        if not managed:
            bak = gtk4 / "gtk.css.pre-purcleshell"
            if not bak.exists():
                shutil.copy2(gtk4_css, bak)
    if not managed:
        atomic_write(gtk4_css, gtk_shell_css())

    patch_settings_ini(gtk3 / "settings.ini", dark)
    patch_settings_ini(gtk4 / "settings.ini", dark)

    scheme = "prefer-dark" if dark else "prefer-light"
    run(["gsettings", "set", "org.gnome.desktop.interface", "color-scheme", scheme])
    theme_proc = run(["gsettings", "get", "org.gnome.desktop.interface", "gtk-theme"])
    theme = "Materia-dark"
    if theme_proc and theme_proc.returncode == 0:
        theme = theme_proc.stdout.strip().strip("'\"") or theme
    # 空切一次才能让已开的 GTK 应用重读 gtk.css
    run(["gsettings", "set", "org.gnome.desktop.interface", "gtk-theme", ""])
    run(["gsettings", "set", "org.gnome.desktop.interface", "gtk-theme", theme])


# ---------- Qt / Kvantum ----------

def qt_scheme_line(colors: dict[str, str], kind: str) -> str:
    require(colors, "text", "surface0", "overlay0", "surface2", "crust", "surface1",
            "onPrimary", "mantle", "base", "shadow", "mauve", "blue", "lavender")
    text = colors["text"] if kind != "disabled" else colors["overlay0"]
    highlight = colors["mauve"] if kind != "inactive" else colors["surface1"]
    values = [
        argb(text),
        argb(colors["surface0"]),
        argb(colors["overlay0"]),
        argb(colors["surface2"]),
        argb(colors["crust"]),
        argb(colors["surface1"]),
        argb(text),
        argb(colors["onPrimary"]),
        argb(text),
        argb(colors["mantle"]),
        argb(colors["base"]),
        argb(colors["shadow"]),
        argb(highlight),
        argb(colors["onPrimary"]),
        argb(colors["blue"]),
        argb(colors["lavender"]),
        argb(colors["surface0"]),
        argb(colors["base"]),
        argb(colors["surface0"]),
        argb(text),
        argb(colors["overlay0"], "80"),
        argb(colors["mauve"]),
    ]
    return ", ".join(values)


def write_qtct_scheme(path: Path, colors: dict[str, str]) -> None:
    content = (
        "[ColorScheme]\n"
        f"active_colors={qt_scheme_line(colors, 'active')}\n"
        f"disabled_colors={qt_scheme_line(colors, 'disabled')}\n"
        f"inactive_colors={qt_scheme_line(colors, 'inactive')}\n"
    )
    atomic_write(path, content)


def patch_qtct_conf(conf: Path, scheme_path: Path) -> None:
    if not conf.exists():
        return
    text = conf.read_text(encoding="utf-8")
    text = patch_ini_key(text, "color_scheme_path", str(scheme_path))
    text = patch_ini_key(text, "custom_palette", "true")
    atomic_write(conf, text if text.endswith("\n") else text + "\n")


def kvantum_general_colors(colors: dict[str, str]) -> str:
    require(colors, "base", "mantle", "surface0", "text", "overlay0", "mauve",
            "onPrimary", "blue", "lavender")
    mapping = {
        "window.color": colors["base"],
        "base.color": colors["mantle"],
        "alt.base.color": colors["surface0"],
        "button.color": colors["surface0"],
        "light.color": colors["text"],
        "mid.light.color": colors["overlay0"],
        "dark.color": colors["base"],
        "mid.color": colors["surface0"],
        "highlight.color": colors["mauve"],
        "inactive.highlight.color": colors["surface0"],
        "text.color": colors["text"],
        "window.text.color": colors["text"],
        "button.text.color": colors["text"],
        "disabled.text.color": colors["overlay0"],
        "tooltip.text.color": colors["text"],
        "highlight.text.color": colors["onPrimary"],
        "link.color": colors["blue"],
        "link.visited.color": colors["lavender"],
        "progress.indicator.text.color": colors["onPrimary"],
    }
    return "".join(f"{k}={v}\n" for k, v in mapping.items())


def write_kvantum(home: Path, colors: dict[str, str]) -> None:
    dest_dir = home / ".config/Kvantum/PurcleShell"
    dest_kv = dest_dir / "PurcleShell.kvconfig"
    dest_svg = dest_dir / "PurcleShell.svg"
    src_dir = home / ".config/Kvantum/Utterly-Nord-Solid"
    src_kv = src_dir / "Utterly-Nord-Solid.kvconfig"
    src_svg = src_dir / "Utterly-Nord-Solid.svg"

    if dest_kv.exists():
        text = dest_kv.read_text(encoding="utf-8")
    elif src_kv.exists():
        text = src_kv.read_text(encoding="utf-8")
        dest_dir.mkdir(parents=True, exist_ok=True)
        if src_svg.exists() and not dest_svg.exists():
            shutil.copy2(src_svg, dest_svg)
    else:
        text = "[%General]\ncomment=Generated by PurcleShell\n"

    text = replace_section(text, "[GeneralColors]", kvantum_general_colors(colors))
    atomic_write(dest_kv, text if text.endswith("\n") else text + "\n")

    kvconf = home / ".config/Kvantum/kvantum.kvconfig"
    if kvconf.exists():
        current = kvconf.read_text(encoding="utf-8")
        current = patch_ini_key(current, "theme", "PurcleShell")
        atomic_write(kvconf, current if current.endswith("\n") else current + "\n")
    else:
        atomic_write(kvconf, "[General]\ntheme=PurcleShell\n")

    run(["kvantummanager", "--set", "PurcleShell"])


def write_qt(home: Path, colors: dict[str, str]) -> None:
    qt6_scheme = home / ".config/qt6ct/colors/purcleshell.conf"
    qt5_scheme = home / ".config/qt5ct/colors/purcleshell.conf"
    write_qtct_scheme(qt6_scheme, colors)
    write_qtct_scheme(qt5_scheme, colors)
    patch_qtct_conf(home / ".config/qt6ct/qt6ct.conf", qt6_scheme)
    patch_qtct_conf(home / ".config/qt5ct/qt5ct.conf", qt5_scheme)
    write_kvantum(home, colors)


# ---------- Zen ----------

def zen_colors_css(colors: dict[str, str]) -> str:
    require(colors, "mauve", "base", "mantle", "text", "surface0", "overlay0")
    return (
        "/* Generated by PurcleShell. Do not edit. */\n"
        ":root {\n"
        f"  --zen-primary-color: {colors['mauve']} !important;\n"
        f"  --lwt-accent-color: {colors['base']} !important;\n"
        f"  --lwt-text-color: {colors['text']} !important;\n"
        f"  --toolbar-bgcolor: {colors['mantle']} !important;\n"
        f"  --toolbar-color: {colors['text']} !important;\n"
        f"  --toolbar-field-background-color: {colors['surface0']} !important;\n"
        f"  --toolbar-field-color: {colors['text']} !important;\n"
        f"  --tab-selected-bgcolor: {colors['surface0']} !important;\n"
        f"  --arrowpanel-background: {colors['mantle']} !important;\n"
        f"  --arrowpanel-color: {colors['text']} !important;\n"
        f"  --ps-base: {colors['base']};\n"
        f"  --ps-text: {colors['text']};\n"
        f"  --ps-mauve: {colors['mauve']};\n"
        "}\n"
    )


def zen_profiles(home: Path) -> list[Path]:
    ini = home / ".zen/profiles.ini"
    root = home / ".zen"
    found: list[Path] = []
    if ini.exists():
        for line in ini.read_text(encoding="utf-8").splitlines():
            if line.startswith("Path="):
                raw = line.split("=", 1)[1].strip()
                path = Path(raw) if raw.startswith("/") else root / raw
                if path.is_dir():
                    found.append(path)
    if not found and root.is_dir():
        for child in root.iterdir():
            if child.is_dir() and (child / "prefs.js").exists():
                found.append(child)
    return found


def ensure_zen_import(path: Path) -> None:
    inner = '@import url("purcleshell-colors.css");\n'
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    atomic_write(path, wrap_marked(existing, inner, MARKER_BEGIN, MARKER_END))


def patch_user_js(path: Path, colors: dict[str, str], dark: bool) -> None:
    require(colors, "mauve")
    inner = (
        'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);\n'
        f'user_pref("zen.theme.accent-color", "{colors["mauve"]}");\n'
        f'user_pref("ui.systemUsesDarkTheme", {1 if dark else 0});\n'
    )
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    atomic_write(path, wrap_marked(existing, inner, USERJS_BEGIN, USERJS_END))


def patch_prefs_js(path: Path, colors: dict[str, str], dark: bool) -> None:
    if not path.exists():
        return
    lock = path.parent / "lock"
    if lock.exists() or (path.parent / ".parentlock").exists():
        return
    text = path.read_text(encoding="utf-8", errors="ignore")
    replacements = {
        "zen.theme.accent-color": f'"{colors["mauve"]}"',
        "toolkit.legacyUserProfileCustomizations.stylesheets": "true",
        "ui.systemUsesDarkTheme": "1" if dark else "0",
    }
    for key, value in replacements.items():
        pattern = re.compile(rf'user_pref\("{re.escape(key)}",\s*[^)]*\);')
        line = f'user_pref("{key}", {value});'
        if pattern.search(text):
            text = pattern.sub(line, text, count=1)
        else:
            if text and not text.endswith("\n"):
                text += "\n"
            text += line + "\n"
    atomic_write(path, text)


def write_zen(home: Path, colors: dict[str, str], dark: bool) -> None:
    css = zen_colors_css(colors)
    profiles = zen_profiles(home)
    if not profiles:
        warn("no Zen profiles found under ~/.zen")
        return
    for profile in profiles:
        chrome = profile / "chrome"
        chrome.mkdir(parents=True, exist_ok=True)
        atomic_write(chrome / "purcleshell-colors.css", css)
        ensure_zen_import(chrome / "userChrome.css")
        ensure_zen_import(chrome / "userContent.css")
        patch_user_js(profile / "user.js", colors, dark)
        patch_prefs_js(profile / "prefs.js", colors, dark)


def main() -> None:
    parser = argparse.ArgumentParser(description="Apply PurcleShell palette to Hyprland/GTK/Qt/Zen")
    parser.add_argument("--dark", default="1", help="1 for dark, 0 for light")
    parser.add_argument("--home", default=os.environ.get("HOME", ""), help="user home")
    parser.add_argument("colors", nargs="+", help="key=#hex pairs")
    args = parser.parse_args()
    if not args.home:
        die("HOME is empty")
    home = Path(args.home).expanduser()
    dark = args.dark not in ("0", "false", "False", "light")
    colors = parse_colors(args.colors)
    write_hyprland(home, colors, dark)
    write_gtk(home, colors, dark)
    write_qt(home, colors)
    write_zen(home, colors, dark)


if __name__ == "__main__":
    try:
        main()
    except BrokenPipeError:
        sys.exit(0)
