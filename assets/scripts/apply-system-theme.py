#!/usr/bin/env python3
"""把 PurcleShell Theme 语义色写到 Hyprland / GTK / Qt / Zen，并尽量热更新。

由 services/SystemTheme.qml 在色板变化时调用。预设与 matugen 共用同一套映射。
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

MARKER_BEGIN = "/* PurcleShell-theme-begin */"
MARKER_END = "/* PurcleShell-theme-end */"
USERJS_BEGIN = "// PurcleShell-theme-begin"
USERJS_END = "// PurcleShell-theme-end"


def die(msg: str, code: int = 1) -> None:
    print(f"apply-system-theme: {msg}", file=sys.stderr)
    raise SystemExit(code)


def warn(msg: str) -> None:
    print(f"apply-system-theme: {msg}", file=sys.stderr)


def norm_hex(value: str) -> str:
    h = value.strip().lower()
    if h.startswith("#"):
        h = h[1:]
    if len(h) == 8:
        h = h[2:] if h[:2] in ("ff", "00") else h[:6]
    if len(h) != 6 or any(c not in "0123456789abcdef" for c in h):
        die(f"bad hex color: {value}")
    return f"#{h}"


def strip_hash(hex_color: str) -> str:
    return hex_color[1:]


def argb(hex_color: str, alpha: str = "ff") -> str:
    return f"#{alpha}{strip_hash(hex_color)}"


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".purcleshell.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)


def run(cmd: list[str], **kwargs) -> subprocess.CompletedProcess | None:
    try:
        return subprocess.run(cmd, check=False, capture_output=True, text=True, **kwargs)
    except FileNotFoundError:
        warn(f"command not found: {cmd[0]}")
        return None


def parse_colors(pairs: list[str]) -> dict[str, str]:
    out: dict[str, str] = {}
    for item in pairs:
        if "=" not in item:
            die(f"expected key=#hex, got: {item}")
        key, value = item.split("=", 1)
        out[key.strip()] = norm_hex(value)
    return out


def require(colors: dict[str, str], *keys: str) -> None:
    missing = [k for k in keys if k not in colors]
    if missing:
        die(f"missing colors: {', '.join(missing)}")


def patch_ini_key(text: str, key: str, value: str) -> str:
    pattern = re.compile(rf"(?m)^{re.escape(key)}\s*=.*$")
    line = f"{key}={value}"
    if pattern.search(text):
        return pattern.sub(line, text, count=1)
    if "[Appearance]" in text:
        return text.replace("[Appearance]", f"[Appearance]\n{line}", 1)
    if text and not text.endswith("\n"):
        text += "\n"
    return text + f"[Appearance]\n{line}\n"


def replace_section(text: str, header: str, body: str) -> str:
    pattern = re.compile(
        rf"{re.escape(header)}\n.*?(?=\n\[|\Z)",
        re.DOTALL,
    )
    block = header + "\n" + body.rstrip() + "\n"
    if pattern.search(text):
        return pattern.sub(block, text, count=1)
    if text and not text.endswith("\n"):
        text += "\n"
    return text + "\n" + block


def wrap_marked(existing: str, inner: str, begin: str, end: str) -> str:
    block = f"{begin}\n{inner.rstrip()}\n{end}\n"
    if begin in existing and end in existing:
        pattern = re.compile(
            re.escape(begin) + r".*?" + re.escape(end) + r"\n?",
            re.DOTALL,
        )
        return pattern.sub(block, existing, count=1)
    if existing and not existing.endswith("\n"):
        existing += "\n"
    if existing.strip():
        return block + "\n" + existing
    return block


# ---------- Hyprland ----------

def write_hyprland(home: Path, colors: dict[str, str], dark: bool) -> None:
    require(colors, "mauve", "surface0", "shadow")
    lua = home / ".config/hypr/lua/colors.lua"
    active = strip_hash(colors["mauve"])
    inactive = strip_hash(colors["surface0"])
    shadow = strip_hash(colors.get("shadow", "#000000"))
    content = (
        "-- Generated by PurcleShell. Do not edit.\n"
        "-- 其它模块通过 require(\"lua.colors\") 引用\n"
        "local colors = {\n"
        f'    active_border   = "rgb({active})",\n'
        f'    inactive_border = "rgb({inactive})",\n'
        f'    shadow          = "rgba({shadow}27)",\n'
        "}\n"
        "\n"
        "return colors\n"
    )
    atomic_write(lua, content)

    # 不用 hyprctl reload：config.reloaded 会把壁纸打回硬编码路径
    cmds = [
        ["hyprctl", "keyword", "general:col.active_border", f"rgb({active})"],
        ["hyprctl", "keyword", "general:col.inactive_border", f"rgb({inactive})"],
        ["hyprctl", "keyword", "decoration:shadow:color", f"rgba({shadow}27)"],
        ["hyprctl", "keyword", "group:col.border_active", f"rgb({active})"],
        ["hyprctl", "keyword", "group:col.border_inactive", f"rgb({inactive})"],
    ]
    _ = dark
    for cmd in cmds:
        proc = run(cmd)
        if proc is not None and proc.returncode != 0:
            err = (proc.stderr or proc.stdout or "").strip()
            if err:
                warn(f"{' '.join(cmd)}: {err}")


